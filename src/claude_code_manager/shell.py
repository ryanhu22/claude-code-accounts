"""The shell wrapper, emitted by `ccm shell-init`.

Claude Code picks its account from CLAUDE_CONFIG_DIR, which has to be set
before it starts, so something in the shell must resolve a directory on every
launch. That is this: a `claude` function that reads the generated routes table
and execs the real binary.

It is deliberately dumb. No Python runs on the hot path, the table is plain
text read with grep, and if this tool is uninstalled or broken the last table
still resolves. Profiles are expanded into path rules when the table is
written, so the shell never needs to know they exist.
"""
from __future__ import annotations

from . import profiles

ZSH = """\
# claude-code-manager: pick the Claude account for this shell.
# Generated by `ccm shell-init`; re-run it after upgrading.
CCM_ROUTES="{routes}"
_cc_project_root() {{  # main checkout for $PWD; a worktree reports its repo
  local gcd root
  gcd=$(git rev-parse --git-common-dir 2>/dev/null)
  if [ -n "$gcd" ]; then
    root=$(cd "$(dirname "$(cd "$gcd" 2>/dev/null && pwd)")" 2>/dev/null && pwd)
  fi
  echo "${{root:-$PWD}}"
}}
_cc_context() {{  # config dir this terminal should launch Claude Code with
  local best="" bestlen=0 line pth dst val cand
  [ -f "$CCM_ROUTES" ] || {{ echo "$HOME/.claude"; return 0; }}
  # A terminal rule was set for exactly this session, so nothing outranks it.
  if [ -n "$TERM_SESSION_ID" ]; then
    val=$(grep "^term:$TERM_SESSION_ID=" "$CCM_ROUTES" 2>/dev/null | tail -1 | cut -d= -f2-)
    [ -n "$val" ] && {{ echo "$val"; return 0; }}
  fi
  # Match the cwd, its physical path (/tmp vs /private/tmp) and the repo root,
  # so a worktree kept outside its repository still follows the repository.
  while IFS= read -r line; do
    case "$line" in
      path:*)
        pth="${{line#path:}}"; dst="${{pth#*=}}"; pth="${{pth%%=*}}"
        for cand in "$PWD" "$(pwd -P)" "$(_cc_project_root)"; do
          case "$cand/" in
            "$pth"/*) [ ${{#pth}} -gt $bestlen ] && {{ best="$dst"; bestlen=${{#pth}}; }} ;;
          esac
        done
        ;;
    esac
  done < "$CCM_ROUTES"
  [ -n "$best" ] && {{ echo "$best"; return 0; }}
  val=$(grep "^default=" "$CCM_ROUTES" 2>/dev/null | tail -1 | cut -d= -f2-)
  echo "${{val:-$HOME/.claude}}"
}}
claude() {{  # an explicit CLAUDE_CONFIG_DIR wins: signing an account in sets it
  CLAUDE_CONFIG_DIR="${{CLAUDE_CONFIG_DIR:-$(_cc_context)}}" command claude "$@"
}}
ccadd() {{  # one time per subscription: sign it into the directory it owns
  local name="$1"
  [ -z "$name" ] && {{ echo "usage: ccadd <account-name>"; return 1; }}
  mkdir -p "{accounts}/$name"
  echo "Opening Claude Code as $name. Type /login, sign in, then /exit."
  CLAUDE_CONFIG_DIR="{accounts}/$name" command claude   # command: never the wrapper
}}
ccresume() {{ CLAUDE_CONFIG_DIR="$(_cc_context)" command claude -c; }}
ccpick()   {{ CLAUDE_CONFIG_DIR="$(_cc_context)" command claude --resume; }}
alias subs='ccm list'
alias ccwhoami='ccm where'
alias ccsessions='ccm sessions'
alias ccprofiles='ccm profiles'
alias ccuse='ccm use'
alias ccpin='ccm use --session'
alias ccunpin='ccm unpin'
"""


def init(accounts_dir: str, shell: str = "zsh") -> str:
    """The snippet to eval from a shell rc file."""
    if shell not in ("zsh", "bash"):
        raise ValueError(f"unsupported shell: {shell}")
    return ZSH.format(routes=profiles.ROUTES, accounts=accounts_dir)
