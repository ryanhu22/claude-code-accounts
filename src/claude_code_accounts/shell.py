"""The shell wrapper, emitted by `ccm shell-init`.

Claude Code picks its account from CLAUDE_CONFIG_DIR, which has to be set
before it starts, so something in the shell must resolve a directory on every
launch. That is this: a `claude` function that reads the generated routes table
and execs the real binary.

It is deliberately dumb. No Python runs on the hot path, the table is plain
text read with grep, and if this tool is uninstalled or broken the last table
still resolves. Profiles are expanded into path rules when the table is
written, so the shell never needs to know they exist.
"""
from __future__ import annotations

from . import profiles

ZSH = """\
# claude-code-accounts: pick the Claude account for this shell.
# Generated by `ccm shell-init`. Deliberately tiny: the routing logic lives in
# {resolver}, which this calls, so changing how routing works
# never requires an already-open terminal to be restarted.
_cc_context() {{ zsh "{resolver}" 2>/dev/null || echo "$HOME/.claude"; }}
claude() {{  # an explicit CLAUDE_CONFIG_DIR wins: signing an account in sets it
  CLAUDE_CONFIG_DIR="${{CLAUDE_CONFIG_DIR:-$(_cc_context)}}" command claude "$@"
}}
ccresume() {{ CLAUDE_CONFIG_DIR="$(_cc_context)" command claude -c; }}
ccpick()   {{ CLAUDE_CONFIG_DIR="$(_cc_context)" command claude --resume; }}
ccadd()    {{ ccm login "$1"; }}
alias subs='ccm list'
alias ccwhoami='ccm where'
alias ccsessions='ccm sessions'
alias ccprofiles='ccm profiles'
alias ccuse='ccm use'
alias ccpin='ccm use --session'
alias ccunpin='ccm unpin'
"""


def init(accounts_dir: str, shell: str = "zsh") -> str:
    """The snippet to eval from a shell rc file."""
    if shell not in ("zsh", "bash"):
        raise ValueError(f"unsupported shell: {shell}")
    profiles.write_resolver()
    return ZSH.format(resolver=profiles.RESOLVER)
